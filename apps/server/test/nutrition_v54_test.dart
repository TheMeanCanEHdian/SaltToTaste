/// The record's ethanol kcal per 100 g by hand: energy less 4/9/4 of its
/// protein, fat and carbohydrate as cached (design §1.1 (A)).
double _ethanolByHand(FdcFood f) {
  final n = f.nutrientsPer100g;
  return n['208']! -
      4 * (n['203'] ?? 0) -
      9 * (n['204'] ?? 0) -
      4 * (n['205'] ?? 0);
}

/// A raw FDC detail's nutrient [number] (test/fixtures/fdc_raw, the live
/// M53 answers copied JSON-equal from .claude/diag/2026-10-07/live47_raw).
double _raw(Map<String, dynamic> food, String number) =>
    ((food['foodNutrients'] as List).cast<Map<String, dynamic>>().firstWhere(
              (n) => (n['nutrient'] as Map)['number'] == number,
            )['amount']
            as num)
        .toDouble();

