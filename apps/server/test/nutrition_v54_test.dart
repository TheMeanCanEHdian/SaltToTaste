      expect(e / _raw(r, '221'), inInclusiveRange(6.80, 7.05), reason: '$id');
      expect(_raw(r, '208') - 7 * _raw(r, '221') < 0, id == 2710699);
    }
    // The SR records print their own factors (3.36 / 8.37 / 3.92): with
    // 6.93 × 221 they reproduce 208 to ±1 (critic 14).
    for (final id in const [175112, 174835, 173200]) {
      final r = raw(id);
      final f = (r['nutrientConversionFactors'] as List)
          .cast<Map<String, dynamic>>()
          .firstWhere((c) => c.containsKey('proteinValue'));
      final atwater =
          (f['proteinValue'] as num) * _raw(r, '203') +
          (f['fatValue'] as num) * _raw(r, '204') +
          (f['carbohydrateValue'] as num) * _raw(r, '205') +
          6.93 * _raw(r, '221');
      expect(atwater, closeTo(_raw(r, '208'), 1), reason: '$id');
    }
