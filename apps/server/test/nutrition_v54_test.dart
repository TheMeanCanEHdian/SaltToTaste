        jsonDecode(File('test/fixtures/fdc_raw/$id.json').readAsStringSync())
            as Map<String, dynamic>;
    FdcFood cached(Map<String, dynamic> r) => FdcFood(
      fdcId: r['fdcId'] as int,
      description: r['description'] as String,
      dataType: r['dataType'] as String,
      nutrientsPer100g: {
        for (final n in const ['208', '203', '204', '205']) n: _raw(r, n),
      },
      portions: const [],
    );
    for (final (id, ethanol) in const [
      (2710689, 71.32), // Wine, white: 82 − 4 × 0.07 − 4 × 2.6
      (2710699, 231.00), // Brandy: 231, no protein, fat or carbohydrate
      (2710692, 104.40), // Wine, dessert, sweet: 160 − 4 × 0.2 − 4 × 13.7
      (175112, 104.52), // SR wine, dessert, dry
      (174835, 72.48), // SR Pinot Noir
      (173200, 64.76), // SR Riesling
