/// [grams] of [fdcId] in kcal, as the totals read the record (its nutrient
/// sibling's values where it has one).
double _kcalOfFood(
  SaltDatabase db,
  int fdcId,
  double grams,
  IngredientLine line,
) {
  final own = knownFood(db, fdcId, line: line)!;
  final sibling = nutrientSiblings[fdcId];
  final food = sibling == null ? own : knownFood(db, sibling)!;
  for (final number in nutrientDefs.first.fdcNumbers) {
    if (food.nutrientsPer100g[number] case final per100?) {
      return per100 * grams / 100;
    }
  }
  return kcalPer100g(food) * grams / 100;
}

/// The row's contribution to its recipe's (gross) energy — the replay's
/// column 17 (rp43 `contribution`): a child row its child's batch energy ×
/// its share, a rendered row its parts, nothing for a skipped, held,
/// below-the-gate or record-less row.
double _kcalOf(SaltDatabase db, IngredientMatchRow r, IngredientLine line) {
  if (r.status == 'skipped') {
    return 0;
  }
  if (r.childRecipeId != null) {
    final n = db.nutritionFor(r.childRecipeId!);
    if (const {'choose_recipe', 'nested_recipe'}.contains(r.hold) ||
        r.childShare == null ||
        n == null) {
      return 0;
    }
    return (batchTotalsOf(n)['energy'] ?? 0) * r.childShare!;
  }
  final grams = r.grams;
  if (r.fdcId == null || grams == null || grams <= 0) {
    return 0;
  }
  if (r.status == 'auto' &&
      (belowConfidenceGate(r.confidence) || r.hold != null)) {
    return 0;
  }
  if (noRecordHolds.contains(r.hold)) {
    return 0;
  }
  if (r.parts != null && r.gramSource != 'override') {
    return [
      for (final p in jsonDecode(r.parts!) as List)
        _kcalOfFood(
          db,
          (p as Map)['fdc_id'] as int,
          (p['grams'] as num).toDouble(),
          line,
        ),
    ].fold(0, (n, k) => n + k);
  }
  return _kcalOfFood(db, r.fdcId!, grams, line);
}

