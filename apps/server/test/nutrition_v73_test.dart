/// [grams] of [fdcId]'s energy as the totals read it (its nutrient
/// sibling's where it has one).
double _ofFood(SaltDatabase db, int fdcId, double grams, IngredientLine line) {
  final sibling = nutrientSiblings[fdcId];
  final food = knownFood(db, sibling ?? fdcId, line: line)!;
  for (final number in nutrientDefs.first.fdcNumbers) {
    if (food.nutrientsPer100g[number] case final per100?) {
      return per100 * grams / 100;
    }
  }
  return kcalPer100g(food) * grams / 100;
}

/// The row's GROSS energy — the replay's column 17 (rp43 `contribution`):
/// a child row its child's batch energy × its share, a rendered row its
/// parts, nothing for a skipped, held, below-the-gate or record-less row.
double _kcal(SaltDatabase db, IngredientMatchRow r, IngredientLine line) {
  if (r.status == 'skipped') {
    return 0;
  }
  if (r.childRecipeId != null) {
    final n = db.nutritionFor(r.childRecipeId!);
    if (const {'choose_recipe', 'nested_recipe'}.contains(r.hold) ||
        r.childShare == null ||
        n == null) {
      return 0;
    }
    return (batchTotalsOf(n)['energy'] ?? 0) * r.childShare!;
  }
  final grams = r.grams;
  if (r.fdcId == null ||
      grams == null ||
      grams <= 0 ||
      (r.status == 'auto' &&
          (belowConfidenceGate(r.confidence) || r.hold != null)) ||
      noRecordHolds.contains(r.hold)) {
    return 0;
  }
  if (r.parts != null && r.gramSource != 'override') {
    return [
      for (final p in jsonDecode(r.parts!) as List)
        _ofFood(
          db,
          (p as Map)['fdc_id'] as int,
          (p['grams'] as num).toDouble(),
          line,
        ),
    ].fold(0, (n, k) => n + k);
  }
  return _ofFood(db, r.fdcId!, grams, line);
}

