/// [row]'s energy as the totals read it: on its nutrient sibling's record
/// where it has one.
String _kcalOf(SaltDatabase db, IngredientMatchRow row, IngredientLine line) {
  final grams = row.grams ?? 0;
  if (grams <= 0) {
    return '0.00';
  }
  final food = switch (nutrientSiblings[row.fdcId]) {
    null => knownFood(db, row.fdcId!, line: line)!,
    final sibling => knownFood(db, sibling)!,
  };
  return (kcalPer100g(food) * grams / 100).toStringAsFixed(2);
}

