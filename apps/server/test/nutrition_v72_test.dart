/// on the record the totals read (its nutrient sibling's where it has one).
double _ofFood(
  SaltDatabase db,
  int fdcId,
  double grams,
  IngredientLine line,
  String key,
) {
  final own = knownFood(db, fdcId, line: line)!;
  final sibling = nutrientSiblings[fdcId];
  final food = sibling == null ? own : knownFood(db, sibling)!;
  final def = nutrientDefs.firstWhere((d) => d.key == key);
